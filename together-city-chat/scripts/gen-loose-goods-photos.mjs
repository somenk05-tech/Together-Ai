#!/usr/bin/env node
/**
 * ── THE LOOSE-GOODS PHOTO BANK, AND WHERE EACH PICTURE CAME FROM ────────────
 *
 *     node scripts/gen-loose-goods-photos.mjs
 *
 * Reads prisma/data/loose-goods-photos.json — the record of one Wikimedia
 * Commons search per product, made on 11 Sep 2026 through a browser on the
 * owner's Mac (the API is not reachable from the build machines) — and writes
 * src/local-services/loose-goods-photos.data.ts, the table the server reads.
 *
 * WHAT THE JSON HOLDS, per product:
 *   key       a slug, ours
 *   aliases   the exact spellings that mean this product — the catalogue's
 *             names AND the kirana spellings a shop types ("toor dal", "tur
 *             dal", "arhar dal"); matching is exact on these, never fuzzy
 *   refs      Agmarknet commodity ids this product covers in the catalogue
 *   search    the Commons search phrase that was run
 *   photo     { title, url, page, licence, artist, width, height } — or null
 *             when nothing suitable came back, and NULL STAYS NULL: a product
 *             with no photo draws no photo, never a placeholder pretending
 *
 * WHICH RESULTS WERE ALLOWED. Only files whose LicenseShortName is CC BY,
 * CC BY-SA, CC0 or public domain; at least 320px a side; scored to prefer the
 * raw good over the cooked dish and over the plant in a field, and to prefer
 * a title that names the product. A human phrase per product, a machine
 * choice per phrase — so a wrong picture is a bug in this file, and fixable
 * by editing the phrase and running the search again.
 *
 * NO PRICES, NO CLAIMS. A picture of red onions is a picture of red onions.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const IN = join(ROOT, 'prisma', 'data', 'loose-goods-photos.json');
const OUT = join(ROOT, 'src', 'local-services', 'loose-goods-photos.data.ts');

const LICENCE_OK = /^(CC BY(-SA)? \d(\.\d)?|CC0|Public domain)/i;

const rows = JSON.parse(readFileSync(IN, 'utf8'));
const kept = [];
for (const r of rows) {
  if (!r.photo) continue;
  if (!LICENCE_OK.test(r.photo.licence)) throw new Error(`${r.key}: licence ${r.photo.licence} is not one the bank accepts`);
  if (!/^https:\/\/upload\.wikimedia\.org\//.test(r.photo.url)) throw new Error(`${r.key}: not a Commons file url`);
  kept.push({
    key: r.key,
    aliases: [...new Set(r.aliases.map((a) => a.toLowerCase().replace(/\s*\(\s*/g, ' (').replace(/\s*\)\s*/g, ') ').replace(/\s+/g, ' ').trim()))],
    refs: r.refs ?? [],
    url: r.photo.url,
    page: r.photo.page,
    licence: r.photo.licence,
    artist: r.photo.artist || null,
  });
}
kept.sort((a, b) => a.key.localeCompare(b.key));

const lines = kept.map((p) => `  ${JSON.stringify(p)},`).join('\n');
writeFileSync(OUT, `/* GENERATED by scripts/gen-loose-goods-photos.mjs from prisma/data/loose-goods-photos.json — do not edit by hand.
   ${kept.length} loose goods, each with ONE Wikimedia Commons photograph, its file page, its licence and its
   photographer. See loose-goods-photos.ts for how a card reaches one and what it may claim. */

export interface LooseGoodsPhoto {
  key: string;
  /** Exact spellings (lowercased) that mean this product. */
  aliases: string[];
  /** Agmarknet commodity ids this product covers in the grocery catalogue. */
  refs: string[];
  url: string;
  page: string;
  licence: string;
  artist: string | null;
}

export const LOOSE_GOODS_PHOTOS: LooseGoodsPhoto[] = [
${lines}
];
`);
console.log(`wrote ${kept.length} photographs (${rows.length - kept.length} products have none) to src/local-services/loose-goods-photos.data.ts`);
